"""Render experiments/divisha/round2_results.md from the aggregate round-two results."""
from __future__ import annotations

import numpy as np

from src.features_r2 import REGIMES


def _f(x, nd=4):
    return "n/a" if x is None else f"{x:.{nd}f}"


def _d(x, nd=4):
    return "n/a" if x is None else f"{x:+.{nd}f}"


def _table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join(["---"] * len(header)) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def render_note(res, manual, m_start, m_end) -> str:
    meta, cfg, facts = res["meta"], res["meta"]["config"], res["facts"]
    configs = res["configs"]
    names = [c["name"] for c in configs]
    folds = [f["fold"] for f in res["folds"]]
    pf, pooled, spf, sp = res["per_fold"], res["pooled"], res["stress_per_fold"], res["stress_pooled"]
    mfl, rt, diag, sel = res["mean_fold_log_loss"], res["runtime_seconds"], res["diagnostics"], res["selection"]
    total_rt = {n: sum(rt[k][n]["fit"] for k in folds) for n in names}
    L = []
    add = L.append

    add("# Round two: logistic regression and attention LSTM under regimes and simulated crashes\n")
    status = ("**Stopped before the reserved evaluation**: the training-prior baseline has the lowest mean-fold "
              "log loss, so no model was selected, the reserved block 801–850 was not evaluated and no prediction "
              "files were written." if sel["stopped"] else
              f"Selected configuration: **{sel['winner']}**. Reserved evaluation on 801–850 run once; final fit on 1–850 "
              "predicted 851–900.")
    add(f"Task `{meta['task_id']}`, owner Divisha, branch `agents/divisha`. {status}\n")
    add("Generated by the command below. The interpretation section is written by hand and preserved across reruns.\n")

    add("## Provenance\n")
    d2 = meta["dataset_round2"]
    add(_table(["Item", "Value"], [
        ["Command", f"`{meta['command']}` (repo root, project venv)"],
        ["Tests before run", meta["tests"]],
        ["Round-two data", f"`{d2['path']}` (not committed; gitignored)"],
        ["Round-two SHA-256 (file on disk)", f"`{d2['sha256_file']}`"],
        ["Round-two SHA-256 (CRLF form, as supplied)", f"`{d2['sha256_crlf_normalised']}`"],
        ["Round-one SHA-256 (CRLF form)", f"`{meta['dataset_round1_sha256_crlf']}` (used only to confirm rows 1–800 are identical)"],
        ["Base commit (origin/main)", f"`{meta['base_commit']}`"],
        ["HEAD at run time", f"`{meta['run_head']}`" + (" (tracked changes uncommitted)" if meta["worktree_dirty_at_run"] else "")],
        ["Feature version", f"`{meta['feature_version']}` ({len(meta['features'])} features)"],
        ["Split manifest", f"`{meta['split_manifest']['path']}`, SHA-256 `{meta['split_manifest']['sha256']}`"],
        ["Python / platform", f"{meta['python']} / {meta['platform']}"],
        ["Dependencies", ", ".join(f"{k} {v}" for k, v in meta["dependencies"].items()) + " (torch CPU wheel)"],
        ["Torch", f"device cpu, {meta['torch_threads']} threads, deterministic algorithms on"],
        ["Seeds", f"global {cfg['seed']}; LSTM {cfg['lstm']['seeds']}; simulator {cfg['simulator']['seeds']}"],
        ["BLAS/OpenMP threads", "OMP, MKL, OPENBLAS, NUMEXPR = 1, set before numerical imports"],
    ]))

    add("\n## Verified round-two facts\n")
    v = facts["volatility_20"]
    fc = facts["formula_check"]
    add(_table(["Fact", "Verified value"], [
        ["Shape / id column", f"{facts['shape'][0]} × {facts['shape'][1]}, `{facts['id_column']}`"],
        ["Labelled / hidden", "rows 1–850 complete; rows 851–900 hide close, return_1d and target only"],
        ["Target rule", f"target = 1 if close[t+1] > close[t] else 0: {facts['target_rule_matches']}/{facts['target_rule_checkable']} checkable rows"],
        ["Class counts (1–850)", f"{facts['target_counts']['ones']} ones, {facts['target_counts']['zeros']} zeros"],
        ["Rows 1–800 vs round one", "identical" if facts["rows_1_800_identical_to_round1"] else "DIFFERENT"],
        ["Rows 801–850 vs round one", ", ".join(f"{k}: {n}/50 differ" for k, n in facts["rows_801_850_cells_differing_from_round1"].items())],
        ["volatility_20, labelled", f"median {v['labelled_median']:.4f}, max {v['labelled_max']:.4f}"],
        ["volatility_20, 851–900", f"{v['pred_min']:.4f} (row 851) rising to ≥ {v['pred_rows_853_900_min']:.4f} from row 853, max {v['pred_max']:.4f}; "
                                   f"max = {v['pred_max_over_labelled_median']:.1f}× labelled median, {v['pred_max_over_labelled_max']:.1f}× labelled max"],
        ["Labelled crash", f"none: labelled volatility_20 never exceeds {v['labelled_max']:.4f}"],
        ["RSI 801–850", f"mean {facts['rsi_14_rows_801_850_mean']:.1f} (high-RSI rally)"],
        ["sma_10 / sma_30 / momentum_5", "include the same row's close (formula check below); visible in 851–900: "
                                          + ("yes" if facts["sma_momentum_visible_in_851_900"] else "no")],
    ]))
    add("\nIndicator formulas recomputed from labelled close/volume (audit only) and compared with the file:\n")
    add(_table(["Indicator", "Formula", "Rows", "Exact", "Max abs error"], [
        ["sma_10", "rolling mean of close, 10", fc["sma_10"]["rows"], fc["sma_10"]["rows_exact"], _f(fc["sma_10"]["max_abs_err"])],
        ["sma_30", "rolling mean of close, 30", fc["sma_30"]["rows"], fc["sma_30"]["rows_exact"], _f(fc["sma_30"]["max_abs_err"])],
        ["momentum_5", "close[t]/close[t-5] − 1", fc["momentum_5"]["rows"], fc["momentum_5"]["rows_exact"], _f(fc["momentum_5"]["max_abs_err"])],
        ["volatility_20", "rolling std (ddof=1) of close pct change, 20", fc["volatility_20"]["rows"], fc["volatility_20"]["rows_exact"], _f(fc["volatility_20"]["max_abs_err"])],
        ["rsi_14", "100 − 100/(1 + mean gain/mean loss), simple 14-row means", fc["rsi_14"]["rows"], fc["rsi_14"]["rows_exact"], _f(fc["rsi_14"]["max_abs_err"])],
        ["volume_z_20", "(volume − rolling mean)/rolling std (ddof=1), 20", fc["volume_z_20"]["rows"], fc["volume_z_20"]["rows_exact"], _f(fc["volume_z_20"]["max_abs_err"])],
    ]))
    add("\nNon-exact rows differ by one unit in the last rounded digit (1e-4). The simulator uses these formulas.\n")

    add("## Features, samples and folds\n")
    w = meta["warmup"]
    add("Features (`" + meta["feature_version"] + "`), all from rows ≤ t and scale-free: "
        + ", ".join(f"`{x}`" for x in meta["features"]) + ".\n")
    add(f"Warmup: the first {w['feature_rows_dropped']} rows have incomplete features (5-row open-to-open return); a sample also needs "
        f"{w['window_context_rows']} earlier feature rows for its 20-day window, so samples start at timestamp {w['first_sample_timestamp']} "
        f"for both LR and LSTM ({w['labelled_rows_unused_as_samples']} labelled rows are never a training sample). LR uses the last row "
        "of each window. Standardization and regime cutoffs are fitted on each fold's real training samples only.\n")
    add(_table(["Fold", "Train", "Purged", "Validate", "n train / val", "Pos. rate train / val", "vol q25 / q75", "rsi q25 / q75",
                "Val n: hv / lv / hr / lr", "Sim aug / stress rows (pos. rate)"],
               [[f["fold"], f"{f['train_range'][0]}–{f['train_range'][1]}", f["purged"], f"{f['eval_range'][0]}–{f['eval_range'][1]}",
                 f"{f['n_train']} / {f['n_val']}", f"{f['train_pos_rate']:.3f} / {f['val_pos_rate']:.3f}",
                 f"{f['cutoffs']['vol_low']:.4f} / {f['cutoffs']['vol_high']:.4f}", f"{f['cutoffs']['rsi_low']:.1f} / {f['cutoffs']['rsi_high']:.1f}",
                 " / ".join(str(f["n_val_regime"][g]) for g in REGIMES),
                 f"{f['n_sim_aug']} ({f['sim_aug_pos_rate']:.3f}) / {f['n_sim_stress']} ({f['sim_stress_pos_rate']:.3f})"]
                for f in res["folds"]]))
    add("\nReserved: train 25–799, purge 800, evaluate 801–850 once. Final: train 25–850, predict 851–900.\n")

    add("## Settings\n")
    a, s, lc = cfg["arms"], cfg["simulator"], cfg["lstm"]
    add(_table(["Item", "Setting"], [
        ["Baseline", "training class-1 frequency per fold"],
        ["LR", "sklearn LogisticRegression(C=1, lbfgs, max_iter=2000); arm B/E: exact epigraph SLSQP, η = 1/(C·Σweights), intercept unpenalised, warm start from A / D"],
        ["LSTM", f"lookback 20, 1 layer, hidden {lc['hidden']}, additive attention, dropout {lc['dropout']}, linear head; AdamW lr {lc['lr']}, "
                 f"weight decay {lc['weight_decay']}, full batch, {lc['epochs']} epochs, no early stopping; seeds {lc['seeds']}, metrics on the seed-averaged p_up"],
        ["Arm A", "mean log loss"],
        ["Arm B", f"(1−λ)·L_overall + λ·max_g L_g + η·Ω, groups high_vol / low_vol / high_rsi / low_rsi, λ ∈ {a['B_lambdas']}; LSTM: exact max of full-batch group means, Ω = weight decay"],
        ["Arm C", f"weight w ∈ {a['C_weights']} on training rows in high_vol or high_rsi, 1 otherwise"],
        ["Arm D", f"real rows + 200×50 simulated crash rows, standard loss; simulated rows' total weight = {a['D_sim_weight_fraction']:.0%} of real rows' total weight"],
        ["Arm E", f"arm D data with arm B objective at λ = {a['E_lambda']}; groups = four real regimes (real rows) + sim_crash (simulated rows)"],
        ["Simulator", f"{s['n_windows']} windows × {s['window']} days per fold from training rows only; burn-in {s['burn_in']} real training prices; "
                      f"block bootstrap (block {s['block']}) of training open-to-open log returns rescaled to m × training median volatility_20, m ∈ {s['multipliers']}; "
                      f"{s['n_drops']} drops of {s['drop_range'][0]:.0%} to {s['drop_range'][1]:.0%}; open gap sd {s['gap_frac']}·σ; high/low scale calibrated on training hl_range; "
                      "volume, volume_z_20 and order_flow resampled jointly from high_vol training rows; indicators recomputed with the verified formulas"],
        ["Stress sets", "a second, independently seeded simulation per fold, never used for training; reported separately"],
        ["Selection", f"{cfg['selection']['rule']}; ties: {cfg['selection']['tie']}"],
    ]))

    add("\n## Summary (real validation rows, 7 development folds, 350 rows pooled)\n")
    add("Stress columns are on synthetic crash windows: **their labels are synthetic**, so they measure robustness to crash-like inputs, "
        "not predictive skill. Fit time is the total over 7 folds (LSTM: all 3 seeds).\n")
    rows = []
    for n in names:
        p, st = pooled[n], sp[n]
        rows.append([n, _f(mfl[n]), _f(p["log_loss"]), _f(p["accuracy"]), _f(p["balanced_accuracy"]), _f(p["roc_auc"]), _f(p["brier"]),
                     _f(p["ece"]), f"{_f(p['worst']['log_loss'])} ({p['worst']['log_loss_regime']})", _f(st["log_loss"]), _f(st["accuracy"]),
                     f"{total_rt[n]:.1f}"])
    add(_table(["Config", "Mean-fold LL", "Pooled LL", "Acc", "Bal. acc", "AUC", "Brier", "ECE", "Worst-regime LL",
                "Stress LL (synthetic)", "Stress acc (synthetic)", "Fit time (s)"], rows))

    add("\n## LSTM seed spread\n")
    add("Per-seed values (seeds 42, 43, 44): mean ± sd [min, max]. Reported metrics elsewhere use the seed-averaged p_up.\n")
    rows = []
    for n in names:
        if not n.startswith("LSTM"):
            continue
        per_seed_ll, per_seed_st = [], []
        for seed in [str(x) for x in cfg["lstm"]["seeds"]]:
            per_seed_ll.append(np.mean([res["lstm_seed_metrics"][k][n][seed]["log_loss"] for k in folds]))
            per_seed_st.append(np.mean([res["lstm_seed_metrics"][k][n][seed]["stress_log_loss"] for k in folds]))
        acc = [np.mean([res["lstm_seed_metrics"][k][n][s_]["accuracy"] for k in folds]) for s_ in [str(x) for x in cfg["lstm"]["seeds"]]]
        fmt = lambda xs: f"{np.mean(xs):.4f} ± {np.std(xs, ddof=1):.4f} [{min(xs):.4f}, {max(xs):.4f}]"
        rows.append([n, fmt(per_seed_ll), fmt(acc), fmt(per_seed_st), _f(mfl[n])])
    add(_table(["Config", "Mean-fold LL per seed", "Mean-fold acc per seed", "Mean-fold stress LL per seed", "Seed-averaged mean-fold LL"], rows))

    add("\n## Robust and augmented arms versus their arm A (pooled real validation)\n")
    add("Negative Δ is better for log loss, Brier, ECE and stress LL; positive Δ is better for accuracy.\n")
    rows = []
    for n in names:
        if n == "baseline_prior" or n.endswith("_A"):
            continue
        ref = n.split("_")[0] + "_A"
        p, r_ = pooled[n], pooled[ref]
        rows.append([n, _d(mfl[n] - mfl[ref]), _d(p["accuracy"] - r_["accuracy"]), _d(p["log_loss"] - r_["log_loss"]),
                     _d(p["brier"] - r_["brier"]), _d(p["ece"] - r_["ece"]), _d(p["worst"]["log_loss"] - r_["worst"]["log_loss"])]
                    + [_d(p["regimes"][g]["log_loss"] - r_["regimes"][g]["log_loss"]) for g in REGIMES]
                    + [_d(sp[n]["log_loss"] - sp[ref]["log_loss"])])
    add(_table(["Config", "Δ mean-fold LL", "Δ Acc", "Δ LL", "Δ Brier", "Δ ECE", "Δ worst LL"] + [f"Δ LL {g}" for g in REGIMES] + ["Δ stress LL"], rows))

    add("\n## Pooled per-regime metrics (real validation rows)\n")
    add("Cells: log loss / accuracy. n = pooled validation rows in the regime (regimes overlap).\n")
    add(_table(["Config"] + [f"{g} (n={pooled[names[0]]['regimes'][g]['n']})" for g in REGIMES],
               [[n] + [f"{_f(pooled[n]['regimes'][g]['log_loss'])} / {_f(pooled[n]['regimes'][g]['accuracy'], 3)}" for g in REGIMES] for n in names]))

    add("\n## Synthetic crash stress test (pooled over folds, 70,000 synthetic rows)\n")
    add("Labels are synthetic (next simulated price > current). Scores show how a configuration behaves on crash-like inputs; "
        "they are not evidence of skill on real crashes and are never mixed into the real-data metrics.\n")
    mults = list(sp[names[0]]["by_multiplier"].keys())
    rows = []
    for n in names:
        st = sp[n]
        rows.append([n, _f(st["log_loss"]), _f(st["accuracy"]), _f(st["roc_auc"]), _f(st["brier"]), _f(st["ece"])]
                    + [f"{_f(st['by_multiplier'][m]['log_loss'])} / {_f(st['by_multiplier'][m]['accuracy'], 3)}" for m in mults])
    add(_table(["Config", "LL", "Acc", "AUC", "Brier", "ECE"] + [f"m = {m}: LL / acc" for m in mults], rows))

    add("\n## Selection (development folds only)\n")
    add(_table(["Rank", "Config", "Mean-fold real LL"], [[i + 1, r["config"], _f(r["mean_fold_log_loss"], 5)] for i, r in enumerate(sel["ranking"])]))
    if sel["stopped"]:
        add("\n**The training-prior baseline has the lowest mean-fold log loss. Per the prespecified rule, the run stopped here:** "
            "no model was picked, the reserved block 801–850 was not evaluated, and no 851–900 prediction files were produced.\n")
    else:
        add(f"\nSelected: **{sel['winner']}**, frozen before the reserved evaluation.\n")

    if res.get("reserved"):
        rv = res["reserved"]
        m, b = rv["metrics"], rv["baseline_metrics"]
        add("## Reserved evaluation (801–850, evaluated once)\n")
        add(f"Train {rv['train_range'][0]}–{rv['train_range'][1]}, purge {rv['purged']}, evaluate {rv['eval_range'][0]}–{rv['eval_range'][1]}. "
            f"Mean RSI in the block is {rv['rsi_14_mean']:.1f}: this is a high-RSI rally, not a crash. Nothing was changed after seeing this result.\n")
        add(_table(["", "Acc", "Bal. acc", "AUC", "LL", "Brier", "ECE", "Worst-regime LL"], [
            [rv["config"], _f(m["accuracy"]), _f(m["balanced_accuracy"]), _f(m["roc_auc"]), _f(m["log_loss"]), _f(m["brier"]), _f(m["ece"]), _f(m["worst"]["log_loss"])],
            ["training prior", _f(b["accuracy"]), _f(b["balanced_accuracy"]), _f(b["roc_auc"]), _f(b["log_loss"]), _f(b["brier"]), _f(b["ece"]), _f(b["worst"]["log_loss"])],
        ]))
        add("\n" + _table(["Regime", "n", "LL", "Acc"], [[g, m["regimes"][g]["n"], _f(m["regimes"][g]["log_loss"]), _f(m["regimes"][g]["accuracy"], 3)] for g in REGIMES]))
    if res.get("final"):
        fn = res["final"]
        add("\n## Final fit (1–850) and predictions for 851–900\n")
        add(f"Config {fn['config']}, {fn['n_train']} training samples. p_up range {fn['p_up_summary']['min']:.3f}–{fn['p_up_summary']['max']:.3f}, "
            f"mean {fn['p_up_summary']['mean']:.3f}; {fn['p_up_summary']['n_class1']} of 50 rows predicted class 1. "
            f"Largest |standardized feature| in 851–900: {fn['max_abs_standardized']:.1f}.\n")
        add("How far 851–900 features lie outside the training range (training = samples 25–850):\n")
        add(_table(["Feature", "Train min", "Train max", "851–900 min", "851–900 max", "Share outside train range", "Median train percentile"],
                   [[k, _f(o["train_min"]), _f(o["train_max"]), _f(o["pred_min"]), _f(o["pred_max"]), f"{o['share_outside_train_range']:.0%}",
                     f"{o['pred_median_train_percentile']:.1f}"] for k, o in fn["out_of_range"].items()]))
        add("\nSubmission files (local only, not committed):\n")
        add(_table(["File", "SHA-256", "Validation"], [
            ["submission_round2_class.csv", f"`{fn['submission_sha256']['submission_round2_class.csv']}`", fn["validation"]["class_file"]],
            ["submission_round2_score.csv", f"`{fn['submission_sha256']['submission_round2_score.csv']}`", fn["validation"]["score_file"]],
        ]))

    add("\n## Per-fold real validation log loss\n")
    add("Each validation block has 50 rows; per-fold differences of a few hundredths are within noise.\n")
    add(_table(["Config"] + folds + ["Mean"], [[n] + [_f(pf[k][n]["log_loss"]) for k in folds] + [_f(mfl[n])] for n in names]))
    add("\n## Per-fold real validation accuracy\n")
    add(_table(["Config"] + folds, [[n] + [_f(pf[k][n]["accuracy"], 3) for k in folds] for n in names]))
    add("\n## Per-fold worst-regime log loss (regime with fewest rows can dominate)\n")
    add(_table(["Config"] + folds, [[n] + [f"{_f(pf[k][n]['worst']['log_loss'], 3)} ({pf[k][n]['worst']['log_loss_regime']})" for k in folds] for n in names]))
    add("\n## Per-fold synthetic stress log loss\n")
    add(_table(["Config"] + folds, [[n] + [_f(spf[k][n]["log_loss"]) for k in folds] for n in names]))

    add("\n## Calibration: pooled reliability (real validation rows)\n")
    add("Cells: n: observed class-1 rate vs mean p_up. Per-fold tables are in the JSON.\n")
    bins = [r["bin"] for r in pooled[names[0]]["reliability"]]
    add(_table(["Config"] + bins + ["ECE"],
               [[n] + [f"{r['n']}: {_f(r['frac_pos'], 3)} vs {_f(r['mean_p'], 3)}" if r["n"] else "0" for r in pooled[n]["reliability"]]
                + [_f(pooled[n]["ece"])] for n in names]))

    add("\n## LR worst-regime (B, E) convergence\n")
    rows = []
    for k in folds:
        for n in names:
            if n.startswith("LR_B") or n.startswith("LR_E"):
                d = diag[k][n]
                rows.append([k, n, "yes" if d["converged"] else "**NO**", d["nit"], f"{d['max_violation']:.1e}", d["active_groups"]])
    add(_table(["Fold", "Config", "Converged", "Iterations", "Max L_g − t", "Active groups"], rows))
    fails = sum(r[2] != "yes" for r in rows)
    add(f"\nConvergence failures: {fails}.\n")

    add("## Runtime\n")
    add(_table(["Config", "Total fit time, 7 folds (s)", "Mean per fold (s)"], [[n, f"{total_rt[n]:.2f}", f"{total_rt[n] / len(folds):.2f}"] for n in names]))

    add("\n## Interpretation\n")
    add(m_start)
    add(manual if manual else "_To be written after reviewing the tables._")
    add(m_end + "\n")

    add("## Warnings and unresolved assumptions\n")
    add("\n".join([
        "- **Target is inferred**: next-row close direction, matching all 849 checkable rows; the organizers' definition is not confirmed.",
        "- **Same-row timing assumed**: open, high, low, volume, sma_10, sma_30, momentum_5, volatility_20, rsi_14, volume_z_20 and order_flow at row t are treated as known when predicting target[t]. sma_10, sma_30 and momentum_5 include close[t]; if the prediction is due before the close, these features are not available in time.",
        "- **Simulator design is mine**: burn-in from real training open prices, open-to-open returns as the return pool, block length 5, the 3×/5× multipliers, 1–2 drops of −8% to −15%, open gap and high/low scaling, and joint resampling of volume/volume_z_20/order_flow are design choices, not estimated from crash data (no labelled crash exists). volume_z_20 is resampled, not recomputed from simulated volume.",
        "- Simulated labels are synthetic. Stress-test scores measure robustness to crash-like inputs, not real predictive skill.",
        "- The simulator was designed from training rows only. After writing it I printed a descriptive comparison of simulated and 851–900 features (simulated ranges are wider); nothing was changed because of it.",
        "- **Reserved-block exposure during development**: while smoke-testing the reserved/final code path (2 folds, 2 LSTM epochs, 4 simulated windows), I evaluated LR_B_lam0.5, LR_E_mc_lam0.5 and LSTM_D_mc on 801–850 before the full run; the LR_B_lam0.5 number is effectively that configuration's real reserved result. The selection rule was already fixed in code and applied mechanically, and nothing was changed afterwards, but the reserved block is not untouched. Those smoke outputs (including throwaway prediction files) were deleted.",
        "- **LSTM settings are fixed, not tuned** (lookback 20, hidden 16, dropout 0.2, lr 1e-3, weight decay 1e-3, 150 full-batch epochs, 3 seeds).",
        "- The regime cutoffs (25%/75%), λ grid, weight grid, 25% simulation weight and λ = 0.5 for arm E were specified, not derived.",
        "- **Output format unknown**: whether organizers want class + confidence or a [−1, 1] score; both files are produced when a model is selected.",
        "- 50-row validation blocks are small and per-regime counts per fold are smaller still; many differences in these tables are within noise.",
        "- LR arm A uses sklearn's default tol=1e-4 (tests show its objective is within 1e-6 of the exact optimum).",
        "- torch was installed from the PyTorch CPU index; on macOS the wheel also contains MPS support, which is never used (device is pinned to cpu).",
        "- Round-one shared code was not on this branch (it was reset to main); metrics and the epigraph LR were reused from the local branch backup/divisha-2514a8f. ROLES.md on main still lists Friday as owner of logistic regression and shared files.",
    ]))

    add("\n## Local artifacts (not committed; `outputs/local/` is gitignored)\n")
    add(_table(["File", "SHA-256"], [[f"`{p}`", f"`{h}`"] for p, h in meta["local_artifacts_sha256"].items()]))
    return "\n".join(L) + "\n"
